PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS beats (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  title TEXT NOT NULL,
  artist TEXT NOT NULL DEFAULT 'VEXEN',
  genre TEXT NOT NULL DEFAULT 'Trap',
  bpm INTEGER NOT NULL DEFAULT 140,
  musical_key TEXT NOT NULL DEFAULT 'Am',
  description TEXT NOT NULL DEFAULT '',
  cover_key TEXT,
  demo_key TEXT,
  mp3_key TEXT,
  wav_key TEXT,
  stems_key TEXT,
  mp3_price INTEGER NOT NULL DEFAULT 500,
  wav_price INTEGER NOT NULL DEFAULT 1000,
  stems_price INTEGER NOT NULL DEFAULT 2000,
  discount INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  public_code TEXT NOT NULL UNIQUE,
  access_token_hash TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  customer_telegram TEXT NOT NULL DEFAULT '',
  delivery_method TEXT NOT NULL DEFAULT 'site',
  telegram_chat_id TEXT NOT NULL DEFAULT '',
  total_amount INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  receipt_key TEXT,
  admin_note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at TEXT,
  delivered_at TEXT
);

CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  order_id INTEGER NOT NULL,
  beat_id INTEGER NOT NULL,
  beat_title TEXT NOT NULL,
  license TEXT NOT NULL CHECK (license IN ('mp3','wav','stems')),
  price INTEGER NOT NULL,
  file_key TEXT,
  FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
  FOREIGN KEY(beat_id) REFERENCES beats(id)
);

CREATE INDEX IF NOT EXISTS idx_beats_active ON beats(active);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items(order_id);


CREATE TABLE IF NOT EXISTS user_favorites (
  telegram_id TEXT NOT NULL,
  beat_id INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (telegram_id, beat_id),
  FOREIGN KEY (beat_id) REFERENCES beats(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_user_favorites_user ON user_favorites(telegram_id, created_at);


CREATE TABLE IF NOT EXISTS playlists (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  title TEXT NOT NULL,
  genre TEXT NOT NULL DEFAULT '',
  cover_key TEXT,
  description TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS playlist_beats (
  playlist_id INTEGER NOT NULL,
  beat_id INTEGER NOT NULL,
  position INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (playlist_id, beat_id),
  FOREIGN KEY (playlist_id) REFERENCES playlists(id) ON DELETE CASCADE,
  FOREIGN KEY (beat_id) REFERENCES beats(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_playlists_active ON playlists(active, created_at);
CREATE INDEX IF NOT EXISTS idx_playlist_beats_order ON playlist_beats(playlist_id, position);


CREATE TABLE IF NOT EXISTS site_content (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  licenses_description TEXT NOT NULL DEFAULT 'Выбери лицензию под свой релиз: MP3 — для быстрого старта, WAV — для высокого качества, STEMS — для гибкой работы со сведением.',
  services_description TEXT NOT NULL DEFAULT 'Помогаю подобрать звук и подготовить материал к релизу.'
);
INSERT OR IGNORE INTO site_content (id) VALUES (1);

CREATE TABLE IF NOT EXISTS services (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Customer accounts: credentials are generated by the Telegram bot on /start register.
CREATE TABLE IF NOT EXISTS customer_accounts (
  telegram_id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash TEXT NOT NULL,
  password_salt TEXT NOT NULL,
  display_name TEXT NOT NULL DEFAULT 'Пользователь',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
